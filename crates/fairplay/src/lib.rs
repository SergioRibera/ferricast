//! FairPlay `fp-setup` key material for AirPlay mirroring senders.
//!
//! AirPlay receivers derived from shairplay (UxPlay, RPiPlay) accept any
//! 164-byte FairPlay key message in the second `fp-setup` round: they store
//! it verbatim and later recover the session AES key from the `ekey` sent in
//! `SETUP` with `playfair_decrypt(key_message, ekey)`. The function is
//! deterministic, so a sender may replay a fixed key message / `ekey` pair
//! as long as it knows the key that decrypts to.
//!
//! [`KEY_MESSAGE`] and [`EKEY`] are arbitrary bytes with valid FairPlay
//! headers; [`AES_KEY`] is the output of `playfair_decrypt` for them,
//! computed with the `playfair` implementation shipped in UxPlay 1.73.6
//! (`lib/playfair`, originally by Esteban Kubata, GPL-3.0). No playfair code
//! is included here, only this one input/output vector.
//!
//! Apple receivers validate the key message cryptographically and will not
//! accept this vector.

#![forbid(unsafe_code)]

/// FairPlay protocol version byte carried at offset 4 of every message.
pub const FAIRPLAY_VERSION: u8 = 3;

/// Header of the 32-byte reply to the second `fp-setup` message; the
/// remaining 20 bytes echo `KEY_MESSAGE[144..164]`.
const REPLY2_HEADER: [u8; 12] = [
    0x46, 0x50, 0x4c, 0x59, 0x03, 0x01, 0x04, 0x00, 0x00, 0x00, 0x00, 0x14,
];

/// Length of the receiver's reply to [`setup_message1`].
pub const REPLY1_LEN: usize = 142;

