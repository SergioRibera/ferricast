//! ferricast's binding to NVIDIA's video engines, NVDEC and NVENC, and the
//! slice of the CUDA driver API they need.
//!
//! Nothing is linked at build time: the driver libraries (`libcuda.so.1`,
//! `libnvcuvid.so.1`, `libnvidia-encode.so.1`; `nvcuda.dll`, `nvcuvid.dll`,
//! `nvEncodeAPI64.dll` on Windows) are loaded on first use ([`loader`]), so a
//! binary built with this crate runs, and reports a typed [`Error`], on
//! machines without an NVIDIA GPU.
//!
//! - [`cuda`]: devices, the shared primary context, streams, events and
//!   pitched device buffers with 2D copies.
//! - [`version`]: NVENC API version negotiation against the installed driver
//!   and the per-version plumbing ([`version::NvencApi`]).
//! - [`encode`]: NVENC sessions.
//! - [`sys`]: the raw generated bindings.
//!
//! The bindings come from FFmpeg's nv-codec-headers (one NVENC module per API
//! version, 11.1 to 13.1) and are regenerated by `scripts/bindings.sh`; see
//! `design/NVCODEC.md` for the decisions behind the crate.
//!
//! ```no_run
//! use ferricast_nvcodec::cuda::{Context, Device};
//! use ferricast_nvcodec::version::ApiVersion;
//!
//! # fn main() -> ferricast_nvcodec::Result<()> {
//! let device = Device::get(0)?;
//! println!("{} at {}", device.name()?, device.pci_bus_id()?);
//! let context = Context::primary(device)?;
//! let api = ApiVersion::negotiate()?;
//! println!("NVENC API {api} on {:?}", context.device());
//! # Ok(())
//! # }
//! ```

