#!/usr/bin/env bash
# Regenerates src/kernels/kernels.ptx from src/kernels/kernels.cu.
#
# The PTX is committed: the crate has no build script and needs no CUDA
# toolkit; the driver JIT-compiles the PTX for whatever GPU it runs on.
#
# Toolchain: nixpkgs' CUDA 12.6 nvcc (the oldest CUDA nixpkgs still has),
# from the nixpkgs this flake locks (`--inputs-from`), with GCC 13 as the
# host compiler (CUDA 12.6 refuses newer ones). nvcc 12.6 writes
# `.version 8.5`, which only R560+ drivers JIT. The device code uses
# nothing newer than PTX ISA 6.0 (CUDA 9, the ISA that introduced the
# current memory model), so the script lowers the `.version` directive to
# 6.0 and lets ptxas verify that claim: ptxas rejects any instruction or
# directive whose ISA is newer than the declared version (checked by hand
# with `shfl.sync` under `.version 5.0`). R470, the oldest driver this
# crate supports (NVENC API 11.1), accepts PTX ISA up to 7.4.
#
#   crates/nvcodec/scripts/kernels.sh
set -euo pipefail

die() {
    echo "kernels.sh: $*" >&2
    exit 1
}

ptx_isa=6.0
target=sm_52

crate=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
flake=$(cd "$crate/../.." && pwd)
source="$crate/src/kernels/kernels.cu"
output="$crate/src/kernels/kernels.ptx"

# The devshell's LD_LIBRARY_PATH breaks the glibc of nixpkgs binaries.
paths=$(NIXPKGS_ALLOW_UNFREE=1 env -u LD_LIBRARY_PATH nix build --impure --no-link \
    --print-out-paths --inputs-from "$flake" \
    nixpkgs#cudaPackages_12_6.cuda_nvcc \
    nixpkgs#cudaPackages_12_6.cuda_cudart \
    nixpkgs#cudaPackages_12_6.cuda_cccl \
    nixpkgs#gcc13) || die "cannot build the CUDA 12.6 toolchain"
pick() { grep -E "$1" <<<"$paths" | head -n 1; }
nvcc_root=$(pick 'cuda_nvcc-[0-9.]+$')
cudart=$(pick 'cuda_cudart-[0-9.]+$')
cccl=$(pick 'cuda_cccl-[0-9.]+$')
gcc=$(pick 'gcc-wrapper-[0-9.]+$')
for path in "$nvcc_root" "$cudart" "$cccl" "$gcc"; do
    [[ -n $path ]] || die "missing a toolchain path in: $paths"
done

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

run() { env -u LD_LIBRARY_PATH "$@"; }

# No fast math: the kernels must match the CPU reference implementations
# (rounding, exact divisions by powers of two).
run "$nvcc_root/bin/nvcc" \
    -ccbin "$gcc/bin/gcc" \
    -I"$cudart/include" -I"$cccl/include" \
    -arch=compute_52 --ptx -std=c++14 \
    -o "$work/kernels.ptx" "$source"

grep -q '^\.version ' "$work/kernels.ptx" || die "no .version directive in nvcc's output"
{
    echo "// Generated by crates/nvcodec/scripts/kernels.sh from kernels.cu: do not edit."
    echo "// nvcc $(run "$nvcc_root/bin/nvcc" --version | sed -n 's/.*release \([0-9.]*\).*/\1/p'), -arch=compute_52, .version lowered to $ptx_isa (verified by ptxas)."
    sed "s/^\.version .*/.version $ptx_isa/" "$work/kernels.ptx"
} >"$work/lowered.ptx"

# The lowered PTX must assemble for the oldest target and the GPUs in use.
for arch in "$target" sm_75 sm_86; do
    run "$nvcc_root/bin/ptxas" -arch="$arch" "$work/lowered.ptx" -o "$work/$arch.cubin" ||
        die "ptxas rejects the PTX for $arch at ISA $ptx_isa"
done

cp "$work/lowered.ptx" "$output"
echo "wrote $output ($(grep -c '^\.visible \.entry' "$output") entry points, PTX ISA $ptx_isa, $target)"
