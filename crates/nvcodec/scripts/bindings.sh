#!/usr/bin/env bash
# Regenerates the committed FFI bindings under src/sys/ from FFmpeg's
# nv-codec-headers (MIT), each tag pinned by commit hash:
#
#   src/sys/cuda.rs           dynlink_cuda.h + scripts/cuda_extra.h (newest tag)
#   src/sys/cuvid.rs          dynlink_cuviddec.h + dynlink_nvcuvid.h (newest tag)
#   src/sys/nvenc/vMA_MI.rs   nvEncodeAPI.h, one module per NVENC API version
#
# It also checks that every NVDEC struct field older SDKs know sits at the
# same offset in the newest header, since one cuvid binding serves every
# driver (see design/NVCODEC.md).
#
# Needs git, bindgen >= 0.72 (for --clang-macro-fallback, which evaluates the
# NVENC struct-version macros) and rustfmt. Without bindgen on PATH but with
# Nix, it re-runs itself inside `nix shell nixpkgs#rust-bindgen`. Run it from
# the workspace devshell so rustfmt matches `cargo fmt`:
#
#   nix develop -c crates/nvcodec/scripts/bindings.sh
set -euo pipefail

die() {
    echo "bindings.sh: $*" >&2
    exit 1
}

if ! command -v bindgen >/dev/null 2>&1; then
    if command -v nix >/dev/null 2>&1 && [[ -z ${FERRICAST_BINDINGS_REEXEC:-} ]]; then
        # The devshell's LD_LIBRARY_PATH breaks the glibc of nixpkgs binaries.
        exec env -u LD_LIBRARY_PATH FERRICAST_BINDINGS_REEXEC=1 \
            nix shell nixpkgs#rust-bindgen -c env -u LD_LIBRARY_PATH "$0" "$@"
    fi
    die "bindgen not found on PATH"
fi
for tool in git rustfmt tar; do
    command -v "$tool" >/dev/null 2>&1 || die "$tool not found on PATH"
done

repo_url=https://github.com/FFmpeg/nv-codec-headers.git
tags=(n11.1.5.4 n12.0.16.2 n12.1.14.1 n12.2.72.0 n13.0.19.1 n13.1.15.0)
declare -A commit=(
    [n11.1.5.4]=85f332a190555b56a1d5d4c070a076c871c0dcea
    [n12.0.16.2]=956b49b0d3a19465e8eb997b7e39c548ad9dd4b2
    [n12.1.14.1]=7c8e7fc751f803c672b42c37d9199c8a4f98b327
    [n12.2.72.0]=c69278340ab1d5559c7d7bf0edf615dc33ddbba7
    [n13.0.19.1]=88fee5c37318c991a8762d423530f91681e32e3a
    [n13.1.15.0]=0a6fba9a2820628b8103464f4c8753ee05838baa
)
declare -A nvenc_module=(
    [n11.1.5.4]=v11_1
    [n12.0.16.2]=v12_0
    [n12.1.14.1]=v12_1
    [n12.2.72.0]=v12_2
    [n13.0.19.1]=v13_0
    [n13.1.15.0]=v13_1
)
newest=n13.1.15.0

crate=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
sys="$crate/src/sys"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

echo "fetching $repo_url"
git clone --quiet --bare "$repo_url" "$work/repo.git"
for tag in "${tags[@]}"; do
    resolved=$(git --git-dir="$work/repo.git" rev-parse "refs/tags/$tag^{commit}")
    [[ $resolved == "${commit[$tag]}" ]] ||
        die "tag $tag now resolves to $resolved, pinned ${commit[$tag]}"
    mkdir -p "$work/$tag"
    git --git-dir="$work/repo.git" archive "${commit[$tag]}" include/ffnvcodec |
        tar -x -C "$work/$tag"
done

headers() { echo "$work/$1/include/ffnvcodec"; }

common=(
    --rust-target 1.88
    --rust-edition 2024
    --formatter none
    --default-enum-style newtype
    --no-prepend-enum-name
    --with-derive-default
    --use-core
)

# $1 = output, $2 = tag, rest = bindgen arguments (header first).
generate() {
    local out=$1 tag=$2
    shift 2
    bindgen "$@" "${common[@]}" \
        --raw-line "// Generated by crates/nvcodec/scripts/bindings.sh from nv-codec-headers $tag (${commit[$tag]}). Do not edit." \
        -o "$out" -- -I"$(headers "$tag")"
}

# --- CUDA driver API ---------------------------------------------------------
cat >"$work/cuda.h" <<EOF
#include "dynlink_cuda.h"
#include "$crate/scripts/cuda_extra.h"
EOF
# The dynlink typedefs are function types (`tcuInit`), which bindgen turns
# into `Option<unsafe extern "C" fn ..>`: exactly what runtime loading needs.
# Layout tests stay: these structs hold no `long`, so the same numbers hold on
# every 64-bit target and the Windows check compiles them too.
generate "$work/cuda.rs" "$newest" "$work/cuda.h" \
    --allowlist-file '.*/(dynlink_cuda|cuda_extra)\.h'

# --- NVDEC (cuvid) -----------------------------------------------------------
cat >"$work/cuvid.h" <<EOF
#include "dynlink_cuda.h"
#include "dynlink_nvcuvid.h"
EOF
# `tcu_ulong` is `unsigned long`: 8 bytes on Linux, 4 on Windows. bindgen
# keeps it as `c_ulong`, which follows the target, but its layout tests
# would pin the Linux sizes, so they are off for this module. The video
# source API (file demuxing, `wchar_t` paths) is not used.
generate "$work/cuvid.rs" "$newest" "$work/cuvid.h" \
    --allowlist-file '.*/dynlink_(cuviddec|nvcuvid)\.h' \
    --blocklist-file '.*/dynlink_cuda\.h' \
    --blocklist-type 'tcuvid(CreateVideoSource|CreateVideoSourceW|DestroyVideoSource|SetVideoSourceState|GetVideoSourceState|GetSourceVideoFormat|GetSourceAudioFormat)' \
    --no-layout-tests \
    --raw-line 'use super::cuda::*;'

# --- NVENC, one module per API version ---------------------------------------
# NvEncodeAPI's two exported entry points are plain declarations; the loader
# resolves them at runtime, so they are declared here as function types.
# GUIDs are `static const` objects in the header, not exported symbols:
# they are emitted as Rust constants below instead.
nvenc_generate() {
    local tag=$1 module=${nvenc_module[$1]}
    local out="$work/$module.rs"
    cat >"$work/nvenc_$module.h" <<EOF
#include "nvEncodeAPI.h"
typedef NVENCSTATUS NVENCAPI tNvEncodeAPIGetMaxSupportedVersion(uint32_t *version);
typedef NVENCSTATUS NVENCAPI tNvEncodeAPICreateInstance(NV_ENCODE_API_FUNCTION_LIST *functionList);
EOF
    mkdir -p "$work/macro_$module"
    # Struct layouts in this header hold no `long`, but at ~4 MB for six
    # versions the layout tests cost more compile time than they catch.
    generate "$out" "$tag" "$work/nvenc_$module.h" \
        --allowlist-file ".*/(nvEncodeAPI\.h|nvenc_$module\.h)" \
        --blocklist-var '.*_GUID' \
        --blocklist-function '.*' \
        --with-derive-custom-struct '_GUID=PartialEq,Eq,Hash' \
        --clang-macro-fallback \
        --clang-macro-fallback-build-dir "$work/macro_$module" \
        --no-layout-tests
    local guids
    guids=$(tr '\n' ' ' <"$(headers "$tag")/nvEncodeAPI.h" |
        grep -oE 'static const GUID +[A-Za-z0-9_]+ *= *\{[^;]*\}' |
        sed -E 's/static const GUID +([A-Za-z0-9_]+) *= *\{ *([0-9a-fA-Fx]+) *, *([0-9a-fA-Fx]+) *, *([0-9a-fA-Fx]+) *, *\{([^}]*)\} *\}/pub const \1: GUID = GUID { Data1: \2, Data2: \3, Data3: \4, Data4: [\5] };/')
    local declared
    declared=$(grep -cE 'static const GUID' "$(headers "$tag")/nvEncodeAPI.h")
    [[ $(grep -c '^pub const' <<<"$guids") == "$declared" ]] ||
        die "$tag: parsed $(grep -c '^pub const' <<<"$guids") of $declared GUIDs"
    printf '%s\n' "$guids" >>"$out"
}
for tag in "${tags[@]}"; do
    nvenc_generate "$tag"
done

# --- NVDEC layout check across SDKs -------------------------------------------
# For every tag, bindgen's layout tests give clang's size and field offsets
# of each cuvid struct. A field an older header has must keep its offset in
# the newest one, so a binding generated from the newest header is read and
# written correctly by older drivers. Reserved fields legitimately shrink as
# new fields take their space; struct tags that were only renamed are
# normalised.
layout() {
    local tag=$1
    bindgen "$work/cuvid.h" --formatter none --ignore-functions -- -I"$(headers "$tag")" |
        grep -oE '"(Size of|Offset of field:) [^"]*"\] \[[^]]*- [0-9]+usize\]' |
        sed -E 's/^"(Size of|Offset of field:) ([^"]*)".* - ([0-9]+)usize\]$/\1|\2 \3/;
                s/^Offset of field:/Offset/; s/^Size of/Size/;
                s/\|_CUVIDAV1SEQHDR/|CUVIDAV1SEQHDR/' |
        LC_ALL=C sort
}
layout "$newest" >"$work/layout_newest"
mismatch=0
for tag in "${tags[@]}"; do
    [[ $tag == "$newest" ]] && continue
    layout "$tag" >"$work/layout_$tag"
    while read -r key old new; do
        case $key in
        Offset*eserved* | Size*) ;;
        *)
            echo "cuvid layout: $key is at $old in $tag but $new in $newest" >&2
            mismatch=1
            ;;
        esac
        if [[ $key == Size* ]]; then
            echo "cuvid layout note: $key is $old bytes in $tag, $new in $newest"
        fi
    done < <(LC_ALL=C join "$work/layout_$tag" "$work/layout_newest" | awk '$2 != $3')
done
((mismatch == 0)) || die "cuvid field offsets differ between SDKs; see design/NVCODEC.md"

# --- install -------------------------------------------------------------------
mkdir -p "$sys/nvenc"
cp "$work/cuda.rs" "$sys/cuda.rs"
cp "$work/cuvid.rs" "$sys/cuvid.rs"
for tag in "${tags[@]}"; do
    cp "$work/${nvenc_module[$tag]}.rs" "$sys/nvenc/${nvenc_module[$tag]}.rs"
done
rustfmt --edition 2024 "$sys/cuda.rs" "$sys/cuvid.rs" "$sys"/nvenc/v*.rs
echo "bindings written to $sys"
